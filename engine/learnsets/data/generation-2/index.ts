//     the same density/shape Generation 1's own curated files already use.
//   - Kept intentionally compact (5-9 entries per species, matching
//     Generation 1's own precedent) rather than exhaustive — TM/HM,
//     breeding, tutor, and event-exclusive moves are out of scope for this
//     phase entirely (level-up only), per this phase's own spec.
