//
//   - Every entry here is a real, thematically-appropriate level-up move for
//     that species, drawn from the full Generation 1-4 move database — used
//     wherever a genuinely Generation-4-introduced move (Aura Sphere, Dragon
//     Pulse, Close Combat, Roost, ...) was the clearly better fit for that
//     species' own signature moves, exactly like Generation 3's own Leaf
//     Blade/Dragon Claw/Calm Mind precedent.
//   - Levels are approximate, not a byte-for-byte transcription of any one
//     game version — chosen to read as a sensible progression, matching
//     Generation 1-3's own density (5-9 entries per species).
//   - Kept intentionally compact, one big file organized in National Dex
//     order — same shape Generation 2/3 already chose over Generation 1's
//     one-file-per-species split.
//   - Level-up only (method: { kind: "level-up" }) — TM/tutor/egg moves are
//     out of scope for this phase, same as every existing generation.
//   - Species whose own pre-evolution belongs to an earlier generation
//     (Ambipom/Mismagius/Honchkrow/Weavile/Magnezone/Lickilicky/Rhyperior/
//     Tangrowth/Electivire/Magmortar/Togekiss/Yanmega/Gliscor/Mamoswine/
//     Porygon-Z/Probopass/Dusknoir — all evolving FROM a Kanto/Johto/Hoenn
//     species per Sinnoh Evolution Phase 2) still get exactly one learnset
//     entry here, keyed by their own species id — their pre-evolution's
//     learnset (aipom, misdreavus, murkrow, sneasel, magneton, lickitung,
//     rhydon, tangela, electabuzz, magmar, togetic, yanma, gligar,
//     piloswine, porygon2, nosepass, dusclops) is unaffected, unchanged, and
//     out of scope for this phase.
//   - Rotom is SIX separate learnset entries (rotom, rotom-heat, rotom-wash,
//     rotom-frost, rotom-fan, rotom-mow — see features/pokemon/forms's Forms
//     architecture), each sharing the same Electric/Ghost core curve but
//     swapping in its own form-appropriate signature move (Overheat/Hydro
//     Pump/Blizzard/Air Slash/Leaf Storm) in place of the base form's
//     Shadow Ball. Giratina is TWO separate learnset entries (giratina,
//     giratina-origin), sharing the same core curve but Origin Form leans
//     into its higher Special Attack with Dragon Pulse where Altered Form
//     uses the physical Dragon Claw — same "similar but independently tuned"
//     precedent Generation 3's own Deoxys forms already established. No
//     Shaymin Sky, Arceus type-plate, Burmy/Wormadam seasonal-cloak,
//     Cherrim Sunshine Form, or Shellos/Gastrodon East Sea learnsets exist —
//     none of those forms exist in the species catalog (Sinnoh Phase 1's own
//     explicit scope), and a learnset needs a real species row to attach to.
