// Generation 7 (Alola Moves & Learnsets Phase 3) — one single file in
// National Dex order, the same shape Generation 2/3/4/5/6's own index.ts
// files already established (never split per-species like Generation 1).
//
// Level-up-only entries, no TM/tutor/egg/event data — out of scope for this
// phase, same as every existing generation. Levels are approximate, chosen
// to read as a sensible progression (2-9 entries per species), matching
// the density Generation 2-6 already use. Entries are drawn from the FULL
// move database (every generation 1-7 move), not restricted to Generation
// 7's own new moves — an Alola species can legitimately know an older move
// when thematically appropriate, same as every prior generation.
//
// Every evolved stage repeats its own pre-evolution's moves at level 1
// (the same "Torterra already knows everything Turtwig had" precedent
// every prior generation's file already established), then adds new moves
// at levels comfortably above the species' own evolution threshold from
// data/pokemon/pokemon-evolutions.ts (Alola Phase 2) — never colliding
// with it. Species reached only via evolution-item (Vikavolt, Alolan
// Sandslash/Ninetales/Exeggutor) or a Branch target (the three Lycanroc
// forms, Solgaleo/Lunala, Alolan Marowak) have no real level floor of
// their own (see engine/evolution-stage-scaling's own "evolution-item/
// Branch targets are fully unrestricted" rule) — their own entries are
// still leveled for flavor, exactly like Roserade/Weavile/Togekiss already
// are in earlier generations.
//
// Rockruff's three Lycanroc forms (lycanroc/lycanroc-midnight/
// lycanroc-dusk, all sharing dex #745 as Forms — data/pokemon/
// generation-7-pokemon-data.ts) are each their own independent learnset,
// sharing the same early Rock-type moveset (the same Pokémon learning to
// fight) but diverging at the level their Branch resolves (25): Midday
// gets Accelerock + Rock Slide, Midnight gets Counter + Sucker Punch, and
// Dusk — genuinely distinct from both — gets Accelerock AND Counter
// together, then Thrash instead of Crunch at the very top. No runtime
// form-switching or hidden day/night value is implemented — this is
// simply three independently leveled species entries, the same
// "never byte-for-byte identical between forms" rule Rotom/Giratina/
// Kyurem/Meloetta/Hoopa already established.
//
// Meltan and Melmetal never appeared in Sun/Moon or Ultra Sun/Ultra Moon
// in the real games (they debuted in Let's Go Pikachu/Eevee and Pokémon
// GO) — per this phase's own explicit instruction, both still get a
// hand-crafted, valid static learnset here using only moves already in
// this project's registry, no Pokémon GO Candy mechanic and no event-only
// move (e.g. Double Iron Bash, out of this phase's Sun/Moon/USUM-move
// scope — see generation-7.completeness.test.ts in engine/moves) involved.
