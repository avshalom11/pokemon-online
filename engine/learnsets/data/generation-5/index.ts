// same "Torterra already knows everything Turtwig had" precedent Generation
// 4's own file established), then adds new moves at levels comfortably
// above the species' own evolution threshold from data/pokemon/
// pokemon-evolutions.ts (Unova Phase 2) — never colliding with it.
//
